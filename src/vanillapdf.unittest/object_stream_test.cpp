static void OpenAndResolve(const unsigned char* data, size_type data_length, biguint_type object_count) {
    HandleGuard<InputOutputStreamHandle, InputOutputStream_Release> io_stream;
    HandleGuard<BufferHandle, Buffer_Release> buffer;
    HandleGuard<FileHandle, File_Release> file;

    ASSERT_EQ(InputOutputStream_CreateFromMemory(io_stream.out()), VANILLAPDF_ERROR_SUCCESS);
    ASSERT_EQ(Buffer_CreateFromData(reinterpret_cast<string_type>(data), data_length, buffer.out()), VANILLAPDF_ERROR_SUCCESS);
    ASSERT_EQ(InputOutputStream_WriteBuffer(io_stream, buffer), VANILLAPDF_ERROR_SUCCESS);
    ASSERT_EQ(InputOutputStream_Flush(io_stream), VANILLAPDF_ERROR_SUCCESS);
    ASSERT_EQ(File_OpenStream(io_stream, "object_stream_cycle", file.out()), VANILLAPDF_ERROR_SUCCESS);

    // The document is broken, so either step is allowed to fail. What it must
    // not do is recurse into the object stream initialization until the stack
    // is exhausted, which takes the whole process down.
    if (File_Initialize(file) != VANILLAPDF_ERROR_SUCCESS) {
        return;
    }

    for (biguint_type object_number = 1; object_number < object_count; ++object_number) {
        ObjectHandle* object = nullptr;
        if (File_GetIndirectObject(file, object_number, 0, &object) == VANILLAPDF_ERROR_SUCCESS) {
            Object_Release(object);
        }
    }
}

TEST(ObjectStream, SelfContainedDoesNotRecurse) {
    OpenAndResolve(OBJSTM_SELF_CONTAINED, sizeof(OBJSTM_SELF_CONTAINED), 6);
}

TEST(ObjectStream, EncryptionDictionaryCycleDoesNotRecurse) {
    OpenAndResolve(OBJSTM_ENCRYPTION_CYCLE, sizeof(OBJSTM_ENCRYPTION_CYCLE), 40);
}

